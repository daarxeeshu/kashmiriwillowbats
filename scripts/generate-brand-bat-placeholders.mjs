/* ── Placeholder artwork for the partner-brand bat ranges ────────────────────────
 *
 * Companion to `generate-product-placeholders.mjs`, which does the same job for the
 * eight equipment categories. This one covers the Kashmir Willow ranges belonging to
 * the brands that had no catalogue of their own: every brand page except KIS's led to
 * an empty grid.
 *
 * Same contract as the equipment generator, and for the same reasons:
 *
 *   - Output is disposable. Every file carries a header saying so, and the real
 *     photograph replaces it at the same path with no code change.
 *   - Do not retouch the output by hand — re-run this instead. A hand-edit is lost
 *     the next time anyone regenerates, and there is no way to tell it happened.
 *   - The cream studio gradient is deliberate and must not become a dark backdrop.
 *     `ProductImageFrame` derives each card's surround from the image's own pixels,
 *     so artwork that is light produces a warm muted card and artwork that is dark
 *     produces a dark one. Matching the one real photograph here would strand these
 *     as black rectangles the moment a real cream-lit shot arrives beside them.
 *
 * The name list below is duplicated in `data/placeholder-brand-bats.ts`, which is the
 * same split the equipment pair already lives with: the data file is what the app
 * reads, this is what draws the pictures, and the slug is the contract between them.
 * If they drift, the card requests an image that is not there — visible immediately,
 * which is why it is an acceptable duplication rather than a hidden one.
 *
 *   node scripts/generate-brand-bat-placeholders.mjs
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "public", "products", "placeholders");

/* Brand → grip colour and willow tone. The variation is the point: eight catalogues
 * drawn from one palette would make every brand page look like the same page, which
 * is exactly the thing a brand catalogue must not do. The tones stay inside the range
 * real Kashmir willow occupies — pale straw through to a deeper honey — so none of
 * them reads as a different timber. */
const BRAND_STYLE = {
  jk: { grip: "#1d4ed8", wood: ["#c9ab7c", "#ecd9b0", "#a8844a"] },
  valleywoods: { grip: "#15803d", wood: ["#c4a878", "#e9d7ae", "#a07f47" ] },
  tramboo: { grip: "#b91c1c", wood: ["#cbae80", "#efdcb6", "#ab8850"] },
  woodford: { grip: "#7c2d12", wood: ["#c0a273", "#e5d2a8", "#9d7c45"] },
  whiteduck: { grip: "#0f766e", wood: ["#cdb184", "#f1dfba", "#ae8b53"] },
  sls: { grip: "#4338ca", wood: ["#c6a878", "#ead8ae", "#a58349"] },
  ib: { grip: "#a16207", wood: ["#c9ad7e", "#eeddb4", "#a9864e"] },
  "a-star": { grip: "#be185d", wood: ["#c2a476", "#e7d4ab", "#9f7e46"] },
};

/* Five models per brand, except JK which already carried one. Names and prices are
 * development stand-ins — see the data file's header. */
const SETS = [
  ["jk", "JK", ["Thunder", "Sixer", "Warrior", "Classic"]],
  ["valleywoods", "Valley Woods", ["Legend", "Pro", "Elite", "Striker", "Classic"]],
  ["tramboo", "Tramboo", ["Pro Series", "Heritage", "Power", "Select", "Club"]],
  ["woodford", "Woodford", ["Premier", "Player", "Blaze", "Classic", "Academy"]],
  ["whiteduck", "Whiteduck", ["Apex", "Storm", "Impact", "Drive", "Club"]],
  ["sls", "SLS", ["Pro Elite", "Titan", "Velocity", "Match", "Academy"]],
  ["ib", "IB", ["International", "Supreme", "Power Play", "Ranger", "Classic"]],
  ["a-star", "A Star", ["Champion", "Pro", "Blaze", "Rising", "Club"]],
];

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** XML-escape. `A & B` in a product name would otherwise close the document. */
function esc(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/* Blade width varies a little per model so a brand's five cards are not five copies
 * of one drawing. Index-derived rather than random, so re-running produces identical
 * files and the diff stays empty when nothing changed. */
function svg({ brandName, model, style, variant }) {
  const [w0, w1, w2] = style.wood;
  const spread = 30 + variant * 2.5;
  const left = 400 - spread;
  const right = 400 + spread;
  const label = esc(`${brandName} ${model}`.toUpperCase());

  return `<!--
  PLACEHOLDER — development artwork, awaiting real product photography.
  Generated by scripts/generate-brand-bat-placeholders.mjs (${brandName}, variant ${variant}).
  Do not retouch by hand: re-run the script, or replace this file with the real
  photograph at the same path and drop \`isPlaceholder\` from the entry in
  data/placeholder-brand-bats.ts.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 1000" width="800" height="1000" role="img">
  <defs>
    <linearGradient id="studio" x1="50%" y1="0%" x2="50%" y2="100%">
      <stop offset="0%" stop-color="#faf8f5"/>
      <stop offset="100%" stop-color="#ebe4da"/>
    </linearGradient>
    <linearGradient id="wood" x1="0%" y1="0%" x2="100%" y2="0%">
      <stop offset="0%" stop-color="${w0}"/>
      <stop offset="50%" stop-color="${w1}"/>
      <stop offset="100%" stop-color="${w2}"/>
    </linearGradient>
    <linearGradient id="grip" x1="0%" y1="0%" x2="100%" y2="0%">
      <stop offset="0%" stop-color="${style.grip}" stop-opacity="0.75"/>
      <stop offset="50%" stop-color="${style.grip}"/>
      <stop offset="100%" stop-color="${style.grip}" stop-opacity="0.75"/>
    </linearGradient>
  </defs>

  <rect width="100%" height="100%" fill="url(#studio)"/>

  <!-- contact shadow -->
  <ellipse cx="400" cy="906" rx="${spread + 26}" ry="12" fill="#1c1b19" opacity="0.13"/>

  <!-- handle -->
  <rect x="388" y="150" width="24" height="250" rx="11" fill="#d8cbb4"/>
  <rect x="388" y="168" width="24" height="214" rx="10" fill="url(#grip)"/>
  ${[0, 1, 2, 3, 4]
    .map((i) => `<rect x="388" y="${186 + i * 40}" width="24" height="7" rx="3" fill="#ffffff" opacity="0.22"/>`)
    .join("\n  ")}

  <!-- splice -->
  <path d="M400 388 L${left + 8} 452 L${right - 8} 452 Z" fill="${w2}" opacity="0.4"/>

  <!-- blade -->
  <path d="M${left} 440 L${right} 440 L${right - 3} 830 Q${right - 5} 886 ${right - 22} 892 L${left + 22} 892 Q${left + 5} 886 ${left + 3} 830 Z" fill="url(#wood)"/>
  <!-- grain -->
  ${[0, 1, 2, 3, 4, 5]
    .map((i) => {
      const x = left + 9 + i * ((spread * 2 - 18) / 5);
      return `<line x1="${x.toFixed(1)}" y1="452" x2="${x.toFixed(1)}" y2="880" stroke="#8a6b3c" stroke-width="1" opacity="0.16"/>`;
    })
    .join("\n  ")}
  <!-- toe guard -->
  <path d="M${left + 22} 892 L${right - 22} 892 L${right - 24} 900 L${left + 24} 900 Z" fill="#3d2914" opacity="0.65"/>

  <text x="400" y="958" fill="#8a847c" font-family="system-ui,-apple-system,sans-serif" font-size="20" font-weight="600" letter-spacing="1.5" text-anchor="middle">${label}</text>
</svg>
`;
}

mkdirSync(OUT_DIR, { recursive: true });

let written = 0;
for (const [brandSlug, brandName, models] of SETS) {
  const style = BRAND_STYLE[brandSlug];
  if (!style) throw new Error(`No BRAND_STYLE entry for "${brandSlug}"`);

  models.forEach((model, index) => {
    const slug = `${brandSlug}-${slugify(model)}`;
    writeFileSync(
      join(OUT_DIR, `${slug}.svg`),
      svg({ brandName, model, style, variant: index }),
      "utf8",
    );
    written += 1;
  });
}

console.log(`Wrote ${written} brand bat placeholders to public/products/placeholders/`);
